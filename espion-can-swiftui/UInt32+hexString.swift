import SwiftUI

//--------------------------------------------------------------------------------------------------

extension UInt32 {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public var hexString : String {
    return String (self & 15, radix: 16, uppercase: true)
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

