import SwiftUI

//--------------------------------------------------------------------------------------------------

extension UInt32 {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public var hex8String : String {
    var result = (self >> 16).hex4String
    result += self.hex4String
    return result.uppercased ()
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public var hex8SepString : String {
    var result = (self >> 16).hex4String
    result += "_"
    result += self.hex4String
    return result.uppercased ()
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

