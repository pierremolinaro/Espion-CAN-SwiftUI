import SwiftUI

//--------------------------------------------------------------------------------------------------

extension View {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  @ViewBuilder nonisolated
  func conditionalKeyboardShortcut (_ inCondition : Bool,
                                    shortcut inShortcut : KeyboardShortcut) -> some View {
    if inCondition {
      self.keyboardShortcut (inShortcut)
    }else{
      self
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

