import SwiftUI

//--------------------------------------------------------------------------------------------------

nonisolated enum CanBusSpeed : Int, Codable, CaseIterable {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  case bps125k = 125_000
  case bps250k = 250_000
  case bps500k = 500_000
  case bps750k = 750_000
  case bps800k = 800_000
  case bps1M = 1_000_000

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  var string : String {
    switch self {
    case .bps1M   : "1 Mbit/s"
    case .bps800k : "800 kbit/s"
    case .bps750k : "750 kbit/s"
    case .bps500k : "500 kbit/s"
    case .bps250k : "250 kbit/s"
    case .bps125k : "125 kbit/s"
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

