import SwiftUI

//--------------------------------------------------------------------------------------------------

extension UInt32 {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public var ipString : String {
    let ip3 = (self >> 24) & 255
    let ip2 = (self >> 16) & 255
    let ip1 = (self >>  8) & 255
    let ip0 = self & 255
    return "\(ip3).\(ip2).\(ip1).\(ip0)"
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

