import SwiftUI

//--------------------------------------------------------------------------------------------------

extension UInt32 : @retroactive RawRepresentable {
  public typealias RawValue = String

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public var rawValue : String {
    return "\(self)"
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public init? (rawValue inRawValue : String) {
    if let v = UInt32 (inRawValue) {
      self = v
    }else{
      return nil
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

