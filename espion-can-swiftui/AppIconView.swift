struct AppIconView : View {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  let title : String

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  var body : some View {
    HStack {
      Image (nsImage: NSApplication.shared.applicationIconImage)
      .resizable ()
      .frame (width: 64, height: 64)
      Spacer ()
      Text (self.title).bold ().controlSize (.large)
      Spacer ()
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

