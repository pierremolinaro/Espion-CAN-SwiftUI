import SwiftUI

//--------------------------------------------------------------------------------------------------

extension UInt16 {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public var hex4String : String {
    var result = ""
    result += String ((self >> 12) & 15, radix: 16)
    result += String ((self >>  8) & 15, radix: 16)
    result += String ((self >>  4) & 15, radix: 16)
    result += String ((self >>  0) & 15, radix: 16)
    return result.uppercased ()
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

