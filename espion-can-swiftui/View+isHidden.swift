import SwiftUI

//--------------------------------------------------------------------------------------------------

extension View {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  @ViewBuilder func isHidden (_ inHidden : Bool) -> some View {
    if inHidden {
      self.hidden ()
    }else{
      self
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

